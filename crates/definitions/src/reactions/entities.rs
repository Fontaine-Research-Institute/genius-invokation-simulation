//! 反应会「生成 / 附属」的实体编号（**只放编号常量，不实现这些实体本身**）。
//!
//! 归属：这些实体各自在自己的牌族 id 区域里，[`crate::reactions::effect::EffectOp`] 的变体
//! 已经隐含牌族（`Status` -> 状态牌族、`Summon` -> 召唤物牌族、
//! `AddCardToHand` -> 行动牌牌族），所以这里只给 `CardId`。
//!
//! 编号来源：游戏内文本描述 `tcgstatuseffects` / `tcgsummons` / `tcgactioncards` 的 `id` 字段
//! （卡面文本与规则书·元素反应·效果一致；**代码里不复制文案**）。
//! 这些实体自己的规则（例如冻结的「受到火/物理伤害时 +2 并移除」、草原核的加伤）
//! 属于**具体状态 / 召唤物卡的实现**，不在本模块。

use crate::base::CardId;

// ----------------------------------------------------------------------
// 状态牌族（角色状态 / 出战状态；共用状态牌族的 id 区域）
// ----------------------------------------------------------------------

/// 冻结（角色状态，id 106）。
///
/// 依据：规则书·元素反应·效果 冻结「使目标角色附属[冻结]状态：角色无法使用技能（状态持续到
/// 回合结束为止）；角色受到火元素伤害或物理伤害时伤害值+2，并移除此状态」。
pub const FROZEN: CardId = CardId::new(106);

/// 护盾（角色状态，id 203）。
///
/// 依据：规则书·元素反应·效果 结晶「提供1点护盾，保护我方出战角色（护盾值可叠加，最多2点）」。
pub const SHIELD: CardId = CardId::new(203);

/// 草原核（出战状态，id 116）。
///
/// 依据：规则书·元素反应·效果 绽放「生成[草原核]：我方对敌方出战角色造成火元素伤害或
/// 雷元素伤害时，伤害值+2。（可用次数1）」。
pub const DENDRO_CORE: CardId = CardId::new(116);

/// 激化领域（出战状态，id 117）。
///
/// 依据：规则书·元素反应·效果 原激化「生成[激化领域]：我方对敌方出战角色造成雷元素伤害或
/// 草元素伤害时，伤害值+1。（可用次数2）」。
pub const CATALYZING_FIELD: CardId = CardId::new(117);

// ----------------------------------------------------------------------
// 召唤物牌族
// ----------------------------------------------------------------------

/// 燃烧烈焰（召唤物，id 115）。
///
/// 依据：规则书·元素反应·效果 燃烧「生成[燃烧烈焰]：结束阶段：造成1点火元素伤害。
/// （可用次数1，最多叠加到2）」。
pub const BURNING_FLAME: CardId = CardId::new(115);

/// 雷暴云（召唤物，id 205）。
///
/// 依据：规则书·元素反应·效果 月感电「生成[雷暴云]：结束阶段：造成2点雷元素伤害。
/// （可用次数1，可叠加，没有上限）」。
pub const THUNDERCLOUD: CardId = CardId::new(205);

/// 月笼（召唤物，id 212）—— **反应不直接生成**：由月笼协奏（行动牌 211）召唤 / 强化。
///
/// 依据：规则书·元素反应·效果 月结晶 + 卡面「月笼协奏：召唤月笼。若我方场上已有月笼，
/// 则使其效果量+1。」
pub const MOONDRIFT: CardId = CardId::new(212);

// ----------------------------------------------------------------------
// 行动牌牌族
// ----------------------------------------------------------------------

/// 月笼协奏（行动牌，id 211）—— 月结晶生成 1 张加入手牌。
///
/// 依据：规则书·元素反应·效果 月结晶「本伤害+1，并生成1张可以召唤并强化月笼的
/// [月笼协奏]加入手牌」；卡片费用 = 2 岩元素骰（卡面）。
pub const MOONDRIFT_HARMONY: CardId = CardId::new(211);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn entity_ids_are_the_rulebook_entities() {
        // 只做「编号常量存在且互不混淆」的钉死；牌族由 EffectOp 变体表达。
        assert_eq!(FROZEN.0.get(), 106);
        assert_eq!(SHIELD.0.get(), 203);
        assert_eq!(DENDRO_CORE.0.get(), 116);
        assert_eq!(CATALYZING_FIELD.0.get(), 117);
        assert_eq!(BURNING_FLAME.0.get(), 115);
        assert_eq!(THUNDERCLOUD.0.get(), 205);
        assert_eq!(MOONDRIFT.0.get(), 212);
        assert_eq!(MOONDRIFT_HARMONY.0.get(), 211);
    }
}
