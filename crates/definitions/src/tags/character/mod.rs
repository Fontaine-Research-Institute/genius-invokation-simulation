//! 角色牌的标签（D54：一个标签一个零大小类型 + 一个文件）。
//!
//! 角色牌**没有类型**（D51），标签直接挂牌族下，再按属性类别分子目录：
//! - `element/`：元素（火 / 水 / 雷 / 草 / 冰 / 风 / 岩）；
//! - `nation/`：国家 / 势力（蒙德 / 璃月 / … / 海乱鬼）；
//! - `arkhe/`：始基力（荒性 Ousia / 芒性 Pneuma）；
//! - `other_weapons.rs`：其他武器。
//!
//! **武器类型标签（单手剑/弓/双手剑/法器/长柄武器）不在这里**：唯一定义在
//! `tags/action_card/equipment/`，角色导入那一份（用户拍板：唯一定义、使用处只导入那一份）。
//! 元素标签与 `base::Element` 不是一回事：前者是标签类型，后者是取值用的数值枚举。
//!
//! 敌人牌也使用这里的元素 / 国家 / 武器类型标签 —— 唯一定义在这里，敌人导入这一份。

pub mod arkhe;
pub mod element;
pub mod nation;
pub mod other_weapons;
