//! timeline —— **触发 / 事件调度的通用机制**（D185 / D186）。
//!
//! 用户口径（D185）：「调度具体，由对应的 families(types) 定义，比如生命值变动，就是角色家庭去
//! 主动调用生命值变动触发的效果」；D186：「不登记效果，登记执行函数指针」。
//!
//! 所以本模块**不认识任何具体时机**，只提供三件机制：
//! 1. **泛型注册表** [`TriggerRegistry`]`<K, E = Effect>`：`K` = 时机键类型（由牌族 / 类型给），
//!    `E` = 效果函数指针类型；**不用 `TypeId`、不用字符串键、没有全局单例**；
//! 2. **有序派发** [`dispatch()`]（单侧）/ [`resolve`]（双方，当前牌手优先）：
//!    排序复用 `rules::ops::order`（规则书·其他规则·结算顺序）；
//! 3. **不执行效果**（D186）：只产出「执行函数指针 + 事件」的有序列表 [`Pending`]；
//!    效果由注册方 / 调用方执行；
//! 4. **结算帧 / 插入式结算**（D194 / D196）：[`Resolution`] 记录「待执行步骤 + `cursor`」；
//!    效果可在当前位置**插入子结算**（新帧），做完回到插入点继续；不是 LIFO 触发栈。
//!    中断 = 保留帧与 `cursor`；确实被击倒 = 丢弃帧；[`Resolution::snapshot`] 导出只读嵌套状态。
//!
//! ## 注册形态（D185 / D186）
//!
//! 一条登记项 [`Trigger`] 包含：
//! - `timing`：**时机键**（家族定义的值：零大小类型或枚举）；
//! - `condition`：**条件函数指针** [`Condition`] = `fn(&Event) -> bool`（不是闭包、不是 trait object）；
//! - `effect`：**执行函数指针**（不是效果数据、不是效果 enum）；默认 [`Effect`] = `fn(&Event)`，
//!   需要局面上下文的家族可把 `E` 设成 `fn(&mut 自家状态, &Event)` 之类；
//! - `owner`：这条触发挂在哪个实体上（派发结果原样带回）；
//! - `source_kind`：`EffectSource`（结算顺序第 2 条：角色牌 / 角色装备和状态 / 阵营出战状态 /
//!   召唤物 / 支援牌）；
//! - `entry`：进场先后（结算顺序第 3 条）。
//!
//! 卡牌 / 状态在**初始化**时把「时机 -> 效果」登记进所属家族的注册表：逐条
//! [`TriggerRegistry::register`]，或从「静态数据 + 函数指针表」整批拷入
//! [`TriggerRegistry::register_all`]（定义侧写 `static [Trigger; N]`，数据只有一份）。
//!
//! ## 结算顺序（规则书·其他规则·结算顺序；权威文档 `结算顺序.md` §一）
//!
//! > **`结算顺序.md` 是唯一权威顺序说明**（暂定，有实测依据再改）：§一 同一时机内 /
//! > §二 插入式结算 / §三 常见插入点 / §五 debug 快照。本模块与下面各小节按它落地。
//!
//! 权威原文（中文）：
//! 1. 「先结算当前牌手的所有卡牌效果，再结算对方牌手的卡牌效果。」
//! 2. 「同属于同一位牌手的卡牌效果，会按照以下顺序进行结算：角色牌、角色装备和状态、阵营出战状态、
//!    召唤物、支援牌。」
//! 3. 「同属于同一位牌手的同类型卡牌效果，会按照进场的先后顺序进行结算。」
//!
//! English（消除中文歧义）: "Card effects of the same type belonging to the same player will be
//! resolved via the order of their entry."
//!
//! 落地（`结算顺序.md` §一）：
//! - 第 1 条 -> [`resolve`]：把「当前牌手」的注册表放第一个参数。两侧是**两个具名实例**
//!   （D34：不用 `Side` 枚举、不用 0/1 编号）；
//! - 第 2 条 -> [`dispatch()`]：复用 `rules::ops::order::resolves_before`（唯一一份顺序表）；
//! - 第 3 条 -> [`dispatch()`]：同一来源类别按 `entry`；
//! - 完全同序 -> **稳定排序**：保持登记顺序（结果可复现）。
//! - 以上与 `结算顺序.md` §一 第 1~4 条逐条对应；顺序常量只在 `rules::ops::order` 一份。
//!
//! ## 怎么用（示例：角色族的「生命值变动」）
//!
//! 通用层**不定义**任何时机枚举；下面只是示例（可运行版本见本模块测试）：
//!
//! ```text
//! // ① 家族自己定义时机键（角色块提供；零大小类型或枚举）
//! enum CharacterTiming { HpChanged, Healed, Defeated }
//!
//! // ② 定义侧写静态登记表：时机 -> 条件函数指针 + 执行函数指针
//! static TRIGGERS: [Trigger<CharacterTiming, MyEffect>; 2] = [
//!     Trigger::new(CharacterTiming::HpChanged, owner, EffectSource::CharacterCard, entry, on_hp_changed),
//!     Trigger::with_condition(CharacterTiming::Healed, owner, EffectSource::CharacterEquipmentOrStatus,
//!                             entry, healed_by_food, on_healed),
//! ];
//!
//! // ③ 初始化：登记进所属家族的注册表（每个牌手一个实例）
//! registry.register_all(&TRIGGERS);
//!
//! // ④ 角色族在自己的数值操作里主动派发；「待执行」由调用方执行
//! let pending = dispatch(&registry, CharacterTiming::HpChanged, &Event::on(who));
//! for item in pending {
//!     // 本层不替你执行；owner 原样带回，供实例级过滤（见下一节）
//!     (item.effect)(state, item.event, item.owner);
//! }
//! ```
//!
//! ## 实例级过滤（同一张卡多实例；Lead 拍板）
//!
//! 同一张卡的多个实例**都登记进同一个家族注册表**（不要求每个实例一张表 —— 那样注册表会变多、
//! 状态会变重，D185）。约定：
//! - 条件 [`Condition`] 保持 `fn(&Event) -> bool`，**不带 owner 参数**（D186）；
//! - 每条登记项带 `owner`：这条触发挂在哪个实例上；
//! - 实例判断放进**效果函数**：调用方执行时把 [`Pending::owner`] 一起传进去，效果函数用它判断
//!   「这条触发是不是属于本次事件的主体」（例如 `owner == event.who` 才生效），不是就直接返回。
//!
//! 示例（同一张卡两个实例，只有一个响应）见 `dispatch.rs` 测试
//! `same_card_two_instances_only_the_owner_responds`：两条登记都命中（时机相同、条件恒真），
//! 但效果函数只让 `owner` 与事件主体一致的那一条真正生效。

//! ## 阶段广播归属（Lead 拍板）
//!
//! **阶段广播不归通用层**：回合开始 / 投掷阶段 / 行动阶段开始 / 行动前 / 行动后 / 行动阶段结束 /
//! 结束阶段 / 回合结束等**阶段时机键**，由**需要广播的块自己定义**，然后调用 [`dispatch()`]
//! （示例 `RoundTiming` 已在测试里跑通）。本模块只提供注册 + 有序派发机制。
//!
//! ## 时机键依据清单（**示例**，不是本模块提供的枚举）
//!
//! 具体时机键由各牌族 / 类型在后续块里定义（D185）；这份清单只把「每个时机的规则书 / 关键字 /
//! 卡面依据」写清楚，供定义时机键时抄依据。阶段类时机同样如此（需要它的块定义成时机键）。
//!
//! - **战斗开始时**：规则书·《七圣召唤》游戏准备「双方各自选择一张自己的『角色牌』作为『出战角色』」；
//!   卡面「战斗开始时」。
//! - **回合开始**：规则书·回合流程 结束阶段「3、开始新的回合！」；其他规则 对局回合上限
//!   「第15回合开始时……」。阶段广播（timeline）只回答「现在到哪个阶段了」。
//! - **投掷阶段**：规则书·回合流程 投掷阶段「每回合的投掷阶段中，会投掷8个『元素骰』。投掷完成后，
//!   还有1次机会选择任意数量元素骰进行『重投』」。
//! - **行动阶段开始**：规则书·进行行动「从『先手牌手』开始，双方『轮流进行行动』」；
//!   权威关键字「元素幻变」：「行动阶段开始时……抓牌、弃置、生成到场上、4 骰转 2+2」。
//! - **行动前 / 选择行动前**：规则书·特殊词条 重击「我方行动开始前，如果元素骰总数为偶数，
//!   则进行的『普通攻击』将被视为『重击』」；卡面「选择行动前」。
//! - **行动后**：规则书·进行行动「完成一个战斗行动后，就会轮到对方行动」；卡面「我方角色行动后」。
//! - **行动阶段结束**：规则书·进行行动 宣布结束「双方都『宣布回合结束』后，行动阶段结束，
//!   进入本回合的『结束阶段』」。
//! - **结束阶段**：规则书·回合流程 结束阶段「1、从『先手牌手』开始，处理在『结束阶段』触发的
