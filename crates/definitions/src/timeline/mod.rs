//!   卡面「受到伤害时：抵消 N 点伤害」（减伤）。
//! - **受伤后**：卡面「受到伤害后」；规则书·其他规则 击倒「当角色的生命值被降为0，则在技能或效果
//!   结算完成后，角色就会被『击倒』」——受伤与击倒分两个时机。
//! - **治疗后**：规则书未单列条目；卡面「治疗后 / 受治疗后」。
//! - **被击倒时**：规则书·其他规则 击倒「当角色的生命值被降为0，则在技能或效果结算完成后，
