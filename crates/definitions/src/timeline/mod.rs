//! - **装备时 / 入场时**：规则书·游戏区域 II(1)「『装备牌』打出给角色后，会附属在角色牌上」；
//!   卡面「装备此牌后 / 入场时」。
//! - **弃置时**：规则书·特殊词条 可用次数「『可用次数』耗尽后，会立刻弃置这张牌」；
