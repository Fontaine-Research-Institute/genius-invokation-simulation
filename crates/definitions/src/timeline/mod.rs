//! - **可用次数耗尽**：规则书·特殊词条 可用次数「每次触发这张牌的效果，都会消耗1次『可用次数』。
//!   『可用次数』耗尽后，会立刻弃置这张牌」。
//! - **持续回合归零**：规则书·特殊词条 持续回合「每个结束阶段，都会使『持续回合』-1。
//!   『持续回合』耗尽后，会立刻弃置这张牌」。
//! - **元素反应后**：规则书·元素反应·规则「对已经具有『元素附着』的目标：（1）造成特定类型的
//!   『元素伤害』时，会引发『元素反应』。（2）以非伤害的形式施加特定类型的『元素附着』时也会引发
//!   『元素反应』」；特殊词条 特技「角色引发元素反应后」。
//!
//! ## 不确定性（D190）
//!
//! 用户口径：「不确定的先不具体确定，如果某个不确定的被观测了，则展开成确定分支+概率」。
//!
//! - **派发不提前展开不确定量**：[`dispatch()`] / [`resolve`] 只做「时机 + 条件」匹配与排序，
//!   输入是**已经发生**的确定事件；不采样、不枚举随机分支、不预先展开；
//! - **观测点才展开**：需要具体值时（例如某效果要取随机元素 / 随机目标），由效果层在**观测点**
//!   返回「分支 + `Fraction` 概率」（分子 / 分母 `ExactNat128`，D152 / D153），**不采样**；
//! - **折叠复用既有语义**：骰子 / 抽牌的折叠已经由各自区域实现（D97 / D98 / D105），本层不重造；
//! - **观测展开是临时的（D191）**：本层不把任何不确定量写进状态；待执行列表 [`Pending`] 是
//!   **临时产物**，调用方执行完丢弃即可。效果若在观测点展开成具体分支，应在不再影响其它计算后
//!   **折叠回紧凑表示**（展开 / 回收成对），不把展开结果永久留在状态里；
//! - 本层本身**没有概率 / 随机 / 浮点**：[`Pending`] 只是「执行函数指针 + 事件」的有序列表，
//!   同一事件 + 同一注册表给出的顺序与内容是确定的。
//!
//! ## 结算帧：插入式结算 + 中断 / 恢复（D194 / D196）
//!
//! 用户口径（D196）：「不是栈，是有些效果会先插入一次别的结算再继续原来的结算」「debug 可以导出触发栈」。
//!
//! 语义（机制原语见 [`Resolution`] / [`Frame`]）：
//! - 当前结算 = 一串**待执行步骤**（[`Queued`]），放在一帧 [`Frame`] 里（步骤 + `cursor`）；
//! - 某些效果会在**当前位置插入**一段新的结算（**子结算** = 压入新的一帧），
//!   父帧的 `cursor` 保留不动；子结算执行完后**回到插入点**继续父帧剩余步骤；
//! - **不是**「触发器后进先出栈」：不按 LIFO 重排已排好的待执行项，原帧步骤顺序不变；
//! - **中断** = 保留帧与 `cursor`；**恢复** = [`Resolution::insert`] 先插入「免于被击倒 + 治疗」子结算，
//!   做完回到 `cursor` 继续；**确实被击倒** = [`Resolution::discard`] 丢弃帧（终止后续）；
//! - **debug 导出**（`结算顺序.md` §五）：[`Resolution::snapshot`] 返回只读嵌套状态
//!   （当前帧 / 每层剩余步骤 / 插入点），不改状态、不含函数指针，供打印 / 导出对照游戏结算顺序。
//!
//! 击倒点的顺序约定（D194 / D195 / D196）：
//! 1. 击倒点把当前结算保留下来（帧与 `cursor` 不动 = 中断）；
//! 2. 击倒那一刻**不插入**「受伤时治疗 1」这类可救回的效果（一击打死就是打死）：
//!    此时角色已被击倒、治疗类效果的**目标已不存在 → 无法执行**
//!    （**不是**触发被屏蔽：触发条件仍然成立，只是没有可操作对象）；
//! 3. 若触发**免于被击倒**：先完成「不视作被击倒」（角色重新成为有效目标），**之后**再给治疗，
//!    然后用 [`Resolution::insert`] 把「免于击倒 + 治疗」作为子结算插入，做完回到 `cursor` 继续；
//! 4. 若最终**确实被击倒**（没有免于被击倒）：[`Resolution::discard`] 丢弃帧，后续真正终止。
//!
//! （以上 = `结算顺序.md` §三「生命值降到 0」那一行；其余常见插入点（受伤时修正 / 扣血后 /
//! 元素附着→反应→反应效果 / 召唤生成 / 结束阶段）由对应数值块在自己的操作里执行，本层只给帧机制。）
//!
//! 本层只提供帧 / 插入 / 恢复 / 丢弃的**机制**；免于击倒的判定与具体治疗由效果层提供
//! （角色侧的时机键与组合方式见 `families::character::trigger`）。

//! ## 不做 / 边界（D185 / D186）
//!
//! - **不定义具体时机**：时机键属于各牌族 / 类型，后续由对应块添加（本模块只做机制）；
//! - **不执行效果**：只返回「函数指针 + 事件」的有序列表，执行由调用方做；
//! - **不持有全局状态**：注册表是普通值（`Vec` 容器，条目全部 `Copy`：函数指针 + 时机键 + `Nat`）；
//! - **不做随机 / 概率 / 浮点**：本层完全确定性；效果若分叉，概率由效果层用
//!   `engine::prob::Fraction` 表达（分子 / 分母 `ExactNat128`，全仓零浮点，D159 / D152 / D153）。

