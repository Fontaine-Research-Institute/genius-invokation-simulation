//! **串联流程**：把各块接成「一局对局怎么走」（开局 / 切换角色 / 击倒清理 / 结束阶段 / 回合开始）。
//!
//! ## 为什么是「纯函数 + 显式待执行」，不是 `&mut`（选型说明）
//!
//! 对外接口一律 **纯函数**：吃 `&DefState`、返回**新 `DefState`**（需要时带分支 + 精确概率），
//! 以及**待执行列表**（各区派发出来、本层不执行，D186）。理由：
//!
//! 1. **与各区一致**：角色区 / 出战状态区 / 装备栏 / 召唤物区 / 支援区 / 牌库的操作都是
//!    「吃 `&self`、返回新状态」，流程层若改成 `&mut` 就要在两套风格间来回穿；
//! 2. **搜索必须能分叉**：开局抓牌 / 换牌天然是多分支（`Vec&lt;(DefState, Fraction)&gt;`），
//!    `&mut` 只能沿一条线推进，分叉时还得自己 clone，纯函数直接给分支 + **精确概率**
//!    （`ExactNat128`，零浮点，D190）；
//! 3. **插入式结算要「不执行也能返回」**：各区派发只排序、不执行（D186），待执行必须原样交回
//!    调用方；纯函数天然把「状态」与「待执行」一起返回，不会留下半执行的状态；
//! 4. **回滚 / 对照方便**：入参一个字节不动，同一局面可以反复派生（debug、单测、对照游戏）。
//!
//! 实现细节上允许先 `let mut next = state.clone();` 再逐区替换 —— 那份克隆**就是返回值**，
//! 没有别名、没有共享可变状态，对外仍然是纯函数（D35：共用实现一份，入口按敌我分两个）。
//!
//! ## 本目录的流程
//!
//! | 文件 | 流程 | 依据 |
//! |---|---|---|
//! | `opening.rs` | 游戏准备：抓 5 张起手（秘传优先）-> 换牌 -> 选首发角色 | 规则书·游戏准备；`rules/ops/opening.rs` |
//! | `switch.rs` | 切换角色：角色区切换 -> 出战状态转移；（骰子支付由上层） | 规则书·战斗行动【切换角色】+ 游戏区域 II(3) |
//! | `defeat.rs` | 击倒清理（D193 归角色块）：移出角色 -> 弃置装备 / 状态（含**饱腹**按时机解除）-> 清空充能 -> 实际最大生命上限回到定义值（D238）-> 记入击倒区（内部记录，供复苏） | 规则书·其他规则 击倒 + 特殊词条 料理 + D238 |
//! | `revive.rs` | 复苏（复活）：击倒区的角色 -> 生命复位 -> 放回角色区 -> 从击倒区移除 | 规则书·特殊词条 料理「复苏」（HP 由卡面给） |
//! | `end_phase.rs` | 结束阶段：出战状态 `tick_end_phase` -> 召唤物 `tick`（持续回合 / 可用次数）-> 双方角色**饱腹**解除 | 规则书·回合流程 结束阶段 + 特殊词条（持续回合 / 可用次数 / 料理） |
//! | `round_begin.rs` | 回合开始：回合数 +1 + 每回合计数清零（`SkillUses::reset_round`）+ 下落攻击标记清除 | 规则书·回合流程「开始新的回合」+ 特殊词条 下落攻击 |
//! | `plunging.rs` | 下落攻击标记的自动清除点：一次战斗行动结束 -> 清除该侧标记 | 规则书·特殊词条 下落攻击（S8.10） |
//!
//! ## 顺序的唯一权威
//!
//! 时机内顺序以工作区 `结算顺序.md`（暂定版）为唯一权威：当前牌手优先 -> 来源类别
//! （角色牌 / 角色装备和状态 / 阵营出战状态 / 召唤物 / 支援牌）-> 进场先后 -> 登记顺序。
//! 本目录只在**流程层面**按它排「先做哪个区」；区内部的派发顺序由各区的 `timeline::dispatch` 保证。
//!
//! ## 执行待执行（D186：派发只排序、不执行）
//!
//! 流程返回的 `Vec&lt;XxxPending&gt;` 由调用方用各区提供的 `execute_*` 执行，例如：
//! - 角色区：`execute_character_zone(&pending.characters, &mut zone)`；
//! - 出战状态区：`execute_combat_status(&pending.combat_status, &mut zone)`；
//! - 装备栏：`execute_equipment(&pending.equipment, &mut zone)`；
//! - 召唤物区：`execute_summon(&pending.summons, &mut zone)`。
//!
//! 待执行里带的是**函数指针 + 事件**，执行时要对**同一个区实例**跑（`Pending.owner` 原样带回，
//! 供效果自己做实例级过滤）。

