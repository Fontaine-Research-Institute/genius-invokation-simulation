//! 构建期数据生成器：**零外部依赖**（本机 cargo 离线；不许加 build-dependencies 里的 crate）。
//!
//! 职责（分工计划.md §4.4.16、结构.md §4.2）：
//! - 读 generated/data/*.json（入库的数据文件，UTF-8）；
//! - 编译期生成 Rust 静态表到 $OUT_DIR/generated_data.rs，由 crate::generated 里
//!   include! 引入；
//! - 生成物随 definitions 的 dll 走，运行期不读文件。
//!
//! 因为不能引第三方 crate，这里自带一个**够用的 JSON 解析器**：只支持这些数据文件用到的
//! 形状（对象 / 数组 / 字符串 / 数字 / 布尔 / null + 标准转义），不追求 RFC 全覆盖。
//! 数据文件缺字段 / 形状不对时直接 panic，让构建失败并给出能定位的报错（不静默兜底）。

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// 数据文件（相对 generated/data/）。
const TERMS_FILE: &str = "terms.json";
const KEYWORDS_FILE: &str = "keywords.json";
const DESCRIPTIONS_FILE: &str = "descriptions.json";

/// JSON 文本对象里的语言键，顺序必须与 crate 里的 Lang::ALL 一致（Zh / En / Ja / Ko）。
const LANG_KEYS: [&str; 4] = ["zh", "en", "ja", "ko"];

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR 必须存在（cargo 提供）"),
    );
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR 必须存在（cargo 提供）"));
    let data_dir = manifest_dir.join("generated").join("data");

    println!("cargo:rerun-if-changed=build.rs");
    // 逐个数据文件登记（Windows 上改文件内容不一定改目录 mtime，不能只盯目录）。
    for file in [TERMS_FILE, KEYWORDS_FILE, DESCRIPTIONS_FILE] {
        println!("cargo:rerun-if-changed={}", data_dir.join(file).display());
    }

    let terms = read_json(&data_dir.join(TERMS_FILE));
    let keywords = read_json(&data_dir.join(KEYWORDS_FILE));
    let descriptions = read_json(&data_dir.join(DESCRIPTIONS_FILE));

    let mut out = String::new();
    out.push_str("// @generated by crates/definitions/build.rs —— 不要手改。\n");
    out.push_str("// 游戏内文本描述（generated/data/*.json，已入库）。\n\n");

    let tag_count = emit_terms(&terms, &mut out);
    let keyword_count = emit_keywords(&keywords, &mut out);
    let corpus_count = emit_descriptions(&descriptions, &mut out);

    writeln!(out, "/// 构建期实际读入的数据文件数量。\npub const GENERATED_DATA_FILES: usize = 3;\n")
        .expect("写字符串不会失败");
    writeln!(out, "/// 标签文本条目数（52；META 方案未定，本表仅测试用）。\npub const TAG_ENTRY_COUNT: usize = {tag_count};\n")
        .expect("写字符串不会失败");
    writeln!(out, "/// 关键字条目数（K 码 → 4 语名字；说明本轮为空）。\npub const KEYWORD_COUNT: usize = {keyword_count};\n")
        .expect("写字符串不会失败");
    writeln!(out, "#[cfg(test)]\n/// 全量文本条数（仅测试用，不进运行时 API）。\npub const TEXT_CORPUS_COUNT: usize = {corpus_count};\n")
        .expect("写字符串不会失败");

    std::fs::write(out_dir.join("generated_data.rs"), out).expect("写 OUT_DIR/generated_data.rs 失败");

    println!(
        "cargo:warning=gi-genius-invokation-definitions generated: tags={tag_count} keywords={keyword_count} corpus_entries={corpus_count}"
    );
}

fn read_json(path: &Path) -> Json {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("读取 {} 失败：{error}", path.display()));
    Parser::parse(&text).unwrap_or_else(|error| panic!("解析 {} 失败：{error}", path.display()))
}

fn entries(json: &Json) -> &[Json] {
    json.get("entries")
        .and_then(Json::as_arr)
        .unwrap_or_else(|| panic!("数据文件顶层必须是 {{\"version\":…,\"entries\":[…]}}"))
}

fn entry_str<'a>(entry: &'a Json, key: &str) -> &'a str {
    entry
        .get(key)
        .and_then(Json::as_str)
        .unwrap_or_else(|| panic!("条目缺少字符串字段 {key:?}：{entry:?}"))
}

fn entry_u32(entry: &Json, key: &str) -> u32 {
    entry
        .get(key)
        .and_then(Json::as_u32)
        .unwrap_or_else(|| panic!("条目缺少无符号整数字段 {key:?}：{entry:?}"))
}

/// 取条目的 texts 对象（缺失时按全缺处理：里面都是 None）。
fn texts_of<'a>(entry: &'a Json, key: &str) -> &'a Json {
    entry.get(key).unwrap_or(&JSON_NULL)
}

const JSON_NULL: Json = Json::Null;

/// terms.json：标签 / 类型 / 伤害元素名的 4 语文本。
fn emit_terms(json: &Json, out: &mut String) -> usize {
    let mut tags: Vec<(String, String)> = Vec::new();
    let mut types: Vec<(String, String)> = Vec::new();
    let mut damages: Vec<(String, String)> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();

    for entry in entries(json) {
        let kind = entry_str(entry, "kind");
        let rust = entry_str(entry, "rust");
        assert!(is_upper_ident(rust), "rust 标识必须是大写蛇形：{rust:?}");
        // 不同 kind 各自命名空间（标签字段 / TYPE_* / DAMAGE_*），只在同类里查重。
        assert!(
            seen.insert(format!("{kind}:{rust}")),
            "{kind} 的 rust 标识重复：{rust:?}"
        );

        let texts = localized_literal(texts_of(entry, "texts"));
        match kind {
            "tag" => {
                let field = rust.to_ascii_lowercase();
                assert!(is_lower_ident(&field), "标签字段名必须是 snake_case：{field:?}");
                tags.push((field, texts));
            }
            "type" => types.push((rust.to_string(), texts)),
            "damage" => damages.push((rust.to_string(), texts)),
            other => panic!("terms.json 里未知 kind：{other:?}"),
        }
    }

    // D67：标签数据**唯一一份**，一个标签一个字段；运行期身份 = 字段地址（&TAGS.field）。
    out.push_str("/// 单个标签的静态文本（D67：字段访问，运行期身份 = &TAGS.<字段>）。\n");
    out.push_str("#[derive(Clone, Copy, Debug)]\npub struct TagText {\n    /// 4 语名字。\npub name: Localized,\n    /// 4 语描述（本轮无数据，全部为空）。\npub description: Localized,\n}\n\n");
    out.push_str("/// 全部标签的静态文本（唯一一份数据；字段访问 = 基址 + 固定偏移，没有查表）。\n");
    out.push_str("#[derive(Clone, Copy, Debug)]\npub struct Tags {\n");
    for (field, _) in &tags {
        writeln!(out, "    /// 见 crate::tags 下对应标签。\npub {field}: TagText,").expect("写字符串不会失败");
    }
    out.push_str("}\n\n");
    out.push_str("/// 标签数据的唯一一份（D67：一个标签一个字段）。\npub static TAGS: Tags = Tags {\n");
    for (field, texts) in &tags {
        writeln!(
            out,
            "    {field}: TagText {{ name: {texts}, description: Localized::EMPTY }},"
        )
        .expect("写字符串不会失败");
    }
    out.push_str("};\n\n");

    for (rust, texts) in &types {
        writeln!(
            out,
            "/// 类型文本（4 语名字；描述本轮为空）。\npub static TYPE_{rust}: TextEntry = TextEntry {{ name: {texts}, description: Localized::EMPTY }};\n"
        )
        .expect("写字符串不会失败");
    }
    for (rust, texts) in &damages {
        writeln!(out, "/// 伤害元素名（4 语）。\npub static DAMAGE_{rust}: Localized = {texts};\n")
            .expect("写字符串不会失败");
    }

    tags.len()
}

/// keywords.json：K 码 → 4 语名字（说明本轮为空）。
fn emit_keywords(json: &Json, out: &mut String) -> usize {
    let mut keywords: Vec<(u32, String, String)> = Vec::new();
    let mut seen: HashSet<u32> = HashSet::new();
    for entry in entries(json) {
        let code = entry_u32(entry, "code");
        assert!(seen.insert(code), "keyword code 重复：{code}");
        let name = localized_literal(texts_of(entry, "name"));
        let description = localized_literal(texts_of(entry, "description"));
        keywords.push((code, name, description));
    }
    keywords.sort_by_key(|(code, _, _)| *code);

    writeln!(out, "/// 全部关键字（按 K 码升序；keyword 用二分查找）。\npub static KEYWORDS: [KeywordDef; {}] = [", keywords.len())
        .expect("写字符串不会失败");
    for (code, name, description) in &keywords {
        writeln!(
            out,
            "    KeywordDef {{ code: KeywordCode::new(Nat::new({code})), name: {name}, description: {description} }},"
        )
        .expect("写字符串不会失败");
    }
    out.push_str("];\n\n");
    keywords.len()
}

/// descriptions.json：卡牌 / 技能 / 状态 / 召唤物 / 敌人 的全量名字与描述（**仅测试用**）。
fn emit_descriptions(json: &Json, out: &mut String) -> usize {
    let mut corpus: Vec<String> = Vec::new();
    for entry in entries(json) {
        let family = entry_str(entry, "family");
        let id = entry_u32(entry, "id");
        let skill_id = entry.get("skill_id").and_then(Json::as_u32).unwrap_or(0);

        for (field, key) in [("name", "name"), ("description", "description")] {
            let texts = texts_of(entry, key);
            if !has_any_text(texts) {
                continue;
            }
            corpus.push(format!(
                "    TextCorpusEntry {{ family: {}, id: Nat::new({id}), skill_id: Nat::new({skill_id}), field: {}, texts: {} }},",
                rust_str_literal(family),
                rust_str_literal(field),
                localized_literal(texts),
            ));
        }
    }

    out.push_str("#[cfg(test)]\n/// 全量文本语料（仅供 D63 全量解析测试用；运行时 API 留到卡牌块）。\n");
    writeln!(out, "pub static TEXT_CORPUS: [TextCorpusEntry; {}] = [", corpus.len())
        .expect("写字符串不会失败");
    for line in &corpus {
        out.push_str(line);
        out.push('\n');
    }
    out.push_str("];\n\n");
    corpus.len()
}

fn has_any_text(texts: &Json) -> bool {
    LANG_KEYS
        .iter()
        .any(|key| texts.get(key).and_then(Json::as_str).is_some())
}

fn localized_literal(texts: &Json) -> String {
    let parts: Vec<String> = LANG_KEYS.iter().map(|key| option_literal(texts, key)).collect();
    if parts.iter().all(|part| part == "None") {
        return String::from("Localized::EMPTY");
    }
    format!("Localized::from_parts({})", parts.join(", "))
}

fn option_literal(texts: &Json, key: &str) -> String {
    match texts.get(key).and_then(Json::as_str) {
        Some(text) => format!("Some({})", rust_str_literal(text)),
        None => String::from("None"),
    }
}

fn is_upper_ident(text: &str) -> bool {
    !text.is_empty()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_uppercase() || byte.is_ascii_digit() || byte == b'_')
}

fn is_lower_ident(text: &str) -> bool {
    !text.is_empty()
        && !text.as_bytes()[0].is_ascii_digit()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
}

/// 把字符串转成 Rust 字符串字面量（含引号），保证生成代码可编译。
fn rust_str_literal(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if (ch as u32) < 0x20 => {
                write!(out, "\\u{{{:x}}}", ch as u32).expect("写字符串不会失败");
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

