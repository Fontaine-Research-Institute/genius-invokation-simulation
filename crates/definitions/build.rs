/// 解析后的 JSON 值（只覆盖数据文件用到的形状）。
#[derive(Debug, Clone, PartialEq)]
enum Json {
    Null,
    Bool(bool),
    /// JSON 数字：**只支持非负整数**（数据里的 id / 计数都是整数；小数 / 指数按不支持跳过并报告）。
    Num(u64),
    Str(String),
    Arr(Vec<Json>),
    Obj(Vec<(String, Json)>),
}

impl Json {
    /// 取对象字段（对象是保序的键值对列表，字段少，线性查找足够）。
    fn get(&self, key: &str) -> Option<&Json> {
        match self {
            Json::Obj(fields) => fields.iter().find(|(k, _)| k == key).map(|(_, v)| v),
            _ => None,
        }
    }

    fn as_str(&self) -> Option<&str> {
        match self {
            Json::Str(text) => Some(text),
            _ => None,
        }
    }

    fn as_arr(&self) -> Option<&[Json]> {
        match self {
            Json::Arr(items) => Some(items),
            _ => None,
        }
    }

    /// 取非负整数（数据里的 id / 计数都是整数；解析阶段已经只保留整数）。
    fn as_u32(&self) -> Option<u32> {
        match self {
            Json::Num(number) if *number <= u32::MAX as u64 => Some(*number as u32),
            _ => None,
        }
    }
}

/// 递归下降 JSON 解析器（字节级扫描；字符串按 UTF-8 校验）。
struct Parser<'a> {
    text: &'a str,
    bytes: &'a [u8],
    pos: usize,
}

impl<'a> Parser<'a> {
    fn parse(text: &'a str) -> Result<Json, String> {
        let mut parser = Parser {
            text,
            bytes: text.as_bytes(),
            pos: 0,
        };
        parser.skip_ws();
        let value = parser.parse_value()?;
        parser.skip_ws();
        if parser.pos != parser.bytes.len() {
            return Err(parser.error("JSON 结束后还有多余内容"));
        }
        Ok(value)
    }

    fn error(&self, message: &str) -> String {
        let consumed = self.text.get(..self.pos.min(self.text.len())).unwrap_or("");
        let line = consumed.matches('\n').count() + 1;
        let col = consumed
            .rfind('\n')
            .map_or(consumed.len(), |newline| consumed.len() - (newline + 1));
        format!("{message}（第 {line} 行，第 {col} 列）")
    }

    fn peek(&self) -> Option<u8> {
        self.bytes.get(self.pos).copied()
    }

    fn bump(&mut self) -> Option<u8> {
        let byte = self.peek()?;
        self.pos += 1;
        Some(byte)
    }

    fn skip_ws(&mut self) {
        while matches!(self.peek(), Some(b' ' | b'\t' | b'\n' | b'\r')) {
            self.pos += 1;
        }
    }

    fn expect(&mut self, byte: u8) -> Result<(), String> {
        if self.peek() == Some(byte) {
            self.pos += 1;
            Ok(())
        } else {
            Err(self.error(&format!("期望字符 {:?}", byte as char)))
        }
    }

    fn parse_value(&mut self) -> Result<Json, String> {
        match self.peek() {
            None => Err(self.error("意外的文件结尾")),
            Some(b'{') => self.parse_object(),
            Some(b'[') => self.parse_array(),
            Some(b'"') => self.parse_string().map(Json::Str),
            Some(b't') => self.parse_keyword("true", Json::Bool(true)),
            Some(b'f') => self.parse_keyword("false", Json::Bool(false)),
            Some(b'n') => self.parse_keyword("null", Json::Null),
            Some(b'-' | b'0'..=b'9') => self.parse_number(),
            Some(other) => Err(self.error(&format!("不认识的 JSON 字符 {:?}", other as char))),
        }
    }

    fn parse_keyword(&mut self, word: &str, value: Json) -> Result<Json, String> {
        if self.bytes[self.pos..].starts_with(word.as_bytes()) {
            self.pos += word.len();
            Ok(value)
        } else {
            Err(self.error(&format!("期望关键字 {word}")))
        }
    }

    fn parse_object(&mut self) -> Result<Json, String> {
        self.expect(b'{')?;
        let mut fields = Vec::new();
        self.skip_ws();
        if self.peek() == Some(b'}') {
            self.pos += 1;
            return Ok(Json::Obj(fields));
        }
        loop {
            self.skip_ws();
            let key = self.parse_string()?;
            self.skip_ws();
            self.expect(b':')?;
            self.skip_ws();
            let value = self.parse_value()?;
            fields.push((key, value));
            self.skip_ws();
            match self.bump() {
                Some(b',') => continue,
                Some(b'}') => break,
                _ => return Err(self.error("对象里期望 ',' 或 '}'")),
            }
        }
        Ok(Json::Obj(fields))
    }

    fn parse_array(&mut self) -> Result<Json, String> {
        self.expect(b'[')?;
        let mut items = Vec::new();
        self.skip_ws();
        if self.peek() == Some(b']') {
            self.pos += 1;
            return Ok(Json::Arr(items));
        }
        loop {
            self.skip_ws();
            items.push(self.parse_value()?);
            self.skip_ws();
            match self.bump() {
                Some(b',') => continue,
                Some(b']') => break,
                _ => return Err(self.error("数组里期望 ',' 或 ']'")),
            }
        }
        Ok(Json::Arr(items))
    }

    fn parse_string(&mut self) -> Result<String, String> {
        self.expect(b'"')?;
        let mut out = String::new();
        loop {
            let byte = self.bump().ok_or_else(|| self.error("字符串没有结束引号"))?;
            match byte {
                b'"' => return Ok(out),
                b'\\' => out.push(self.parse_escape()?),
                _ if byte < 0x20 => return Err(self.error("字符串里出现未转义的控制字符")),
                _ => {
                    // 非转义部分按 UTF-8 原样拷贝：回退 1 字节后按字符解码。
                    self.pos -= 1;
                    let rest = self
                        .text
                        .get(self.pos..)
                        .ok_or_else(|| self.error("UTF-8 边界错误"))?;
                    let ch = rest.chars().next().ok_or_else(|| self.error("字符串意外结束"))?;
                    out.push(ch);
                    self.pos += ch.len_utf8();
                }
            }
        }
    }

    fn parse_escape(&mut self) -> Result<char, String> {
        let byte = self.bump().ok_or_else(|| self.error("转义符后没有字符"))?;
        let ch = match byte {
            b'"' => '"',
            b'\\' => '\\',
            b'/' => '/',
            b'b' => '\u{0008}',
            b'f' => '\u{000c}',
            b'n' => '\n',
            b'r' => '\r',
            b't' => '\t',
            b'u' => return self.parse_unicode_escape(),
            _ => return Err(self.error("不支持的转义符")),
        };
        Ok(ch)
    }

    fn parse_unicode_escape(&mut self) -> Result<char, String> {
        let first = self.parse_hex4()?;
        // 代理对：高代理后面必须紧跟 \uDC00..\uDFFF。
        if (0xD800..=0xDBFF).contains(&first) {
            if self.peek() != Some(b'\\') || self.bytes.get(self.pos + 1) != Some(&b'u') {
                return Err(self.error("UTF-16 高代理后缺少 \\u 低代理"));
            }
            self.pos += 2;
            let second = self.parse_hex4()?;
            if !(0xDC00..=0xDFFF).contains(&second) {
                return Err(self.error("UTF-16 低代理范围错误"));
            }
            let combined = 0x10000 + ((first - 0xD800) << 10) + (second - 0xDC00);
            return char::from_u32(combined).ok_or_else(|| self.error("非法 Unicode 码点"));
        }
        if (0xDC00..=0xDFFF).contains(&first) {
            return Err(self.error("孤立的 UTF-16 低代理"));
        }
        char::from_u32(first).ok_or_else(|| self.error("非法 Unicode 码点"))
    }

    fn parse_hex4(&mut self) -> Result<u32, String> {
        let mut value = 0u32;
        for _ in 0..4 {
            let byte = self.bump().ok_or_else(|| self.error("\\u 后不足 4 位十六进制"))?;
            let digit = match byte {
                b'0'..=b'9' => u32::from(byte - b'0'),
                b'a'..=b'f' => 10 + u32::from(byte - b'a'),
                b'A'..=b'F' => 10 + u32::from(byte - b'A'),
                _ => return Err(self.error("\\u 后不是十六进制数字")),
            };
            value = value * 16 + digit;
        }
        Ok(value)
    }

    /// 解析数字：**只支持非负整数**（逐位累乘，检查溢出）。
    ///
    /// 小数 / 指数 / 负数在本项目的数据里都不需要：扫描时保持解析位置正确，
    /// 然后把该值当作「不支持」跳过（`Json::Null`），并在生成时用 `cargo:warning` 报告。
    fn parse_number(&mut self) -> Result<Json, String> {
        let start = self.pos;
        let negative = self.peek() == Some(b'-');
        if negative {
            self.pos += 1;
        }
        let mut value: u64 = 0;
        let mut overflow = false;
        match self.peek() {
            Some(b'0') => {
                self.pos += 1;
            }
            Some(b'1'..=b'9') => {
                while let Some(byte @ b'0'..=b'9') = self.peek() {
                    self.pos += 1;
                    match value
                        .checked_mul(10)
                        .and_then(|acc| acc.checked_add(u64::from(byte - b'0')))
                    {
                        Some(next) => value = next,
                        None => overflow = true,
                    }
                }
            }
            _ => return Err(self.error("数字格式错误")),
        }
        let mut unsupported = false;
        if self.peek() == Some(b'.') {
            unsupported = true;
            self.pos += 1;
            let digits_start = self.pos;
            while matches!(self.peek(), Some(b'0'..=b'9')) {
                self.pos += 1;
            }
            if self.pos == digits_start {
                return Err(self.error("小数点后没有数字"));
            }
        }
        if matches!(self.peek(), Some(b'e' | b'E')) {
            unsupported = true;
            self.pos += 1;
            if matches!(self.peek(), Some(b'+' | b'-')) {
                self.pos += 1;
            }
            let digits_start = self.pos;
            while matches!(self.peek(), Some(b'0'..=b'9')) {
                self.pos += 1;
            }
            if self.pos == digits_start {
                return Err(self.error("指数部分没有数字"));
            }
        }
        let raw = self
            .text
            .get(start..self.pos)
            .ok_or_else(|| self.error("数字切片越界"))?;
        if negative || unsupported || overflow {
            println!(
                "cargo:warning=JSON 数字只支持非负整数，已按不支持跳过：{raw}"
            );
            return Ok(Json::Null);
        }
        Ok(Json::Num(value))
    }
}
